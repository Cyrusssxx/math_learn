def main():
    d = json.load(open(PATH, encoding='utf-8'))
    seen = set()
    for p in d:
        pn = int(p['id'].split('-')[-1])
        for s in p['sections']:
            for q in s['questions']:
                key = (pn, q['no'])
                if key not in IDEAS:
                    raise SystemExit('缺少思路: %s' % (key,))
                q['idea'] = '「思路」：' + IDEAS[key]
                seen.add(key)
    extra = set(IDEAS) - seen
    if extra:
        raise SystemExit('多余思路键: %s' % sorted(extra))
    json.dump(d, open(PATH, 'w', encoding='utf-8'), ensure_ascii=False)
    print('写入思路', len(seen), '条')

if __name__ == '__main__':
    main()
