# 2. 修正与补全 Note 2: 一元微分 (极值与拐点充分条件)
# =========================================================================
n2 = notes[2]
old_md2 = n2['md']

old_ext2 = """- **极值充分**
  - 条件一：$f$ 在 $x_0$ 连续，$f'$ 在 $x_0$ 左右去心邻域内**异号** ⟹ 极值
  - 条件二：$f'(x_0)=0,\ f''(x_0)\\neq0$——$f''(x_0)>0$ 极小值；$f''(x_0)<0$ 极大值
  - 条件三（n 阶判别）：$f'(x_0)=\\cdots=f^{(n-1)}(x_0)=0,\ f^{(n)}(x_0)\\neq0$（$n\\ge2$）——$n$ 为偶数 ⟹ 极值（$f^{(n)}(x_0)>0$ 极小值，$f^{(n)}(x_0)<0$ 极大值）；$n$ 为奇数 ⟹ **不取得极值**（例 $f=x^4$ 取极小，$f=x^3$ 无极值）"""

new_ext2 = """- **极值充分条件（三大充分条件判定法）**
  - **第一充分条件（一阶导变号法）**：设 $f(x)$ 在 $x_0$ 处连续，在某去心邻域内可导：
    - 若 $f'(x)$ 在 $x_0$ 左侧 $>0$、右侧 $<0$（“左正右负”），则 $x_0$ 为**极大值点**；
    - 若 $f'(x)$ 在 $x_0$ 左侧 $<0$、右侧 $>0$（“左负右正”），则 $x_0$ 为**极小值点**；
    - 若 $f'(x)$ 在左右两侧符号相同，则 $x_0$ **不是极值点**。
    - 💡 优势：不仅适用于驻点（$f'(x_0)=0$），同样适用于**导数不存在的连续点**（如 $f(x)=|x|$ 在 $x=0$ 处）。
  - **第二充分条件（二阶导二分法）**：设 $f(x)$ 在 $x_0$ 处二阶可导，且 $f'(x_0)=0$：
    - 若 $f''(x_0)<0$，则 $x_0$ 为**极大值点**；
    - 若 $f''(x_0)>0$，则 $x_0$ 为**极小值点**；
    - ⚠️ 若 $f''(x_0)=0$，此法**失效**，必须改用第一或第三充分条件。
  - **第三充分条件（高阶导数判别法）**：设 $f(x)$ 在 $x_0$ 处具有 $n$ 阶导数（$n\\ge2$），且
    $$f'(x_0)=f''(x_0)=\\cdots=f^{(n-1)}(x_0)=0,\\quad f^{(n)}(x_0)\\neq0$$
    - 若 **$n$ 为偶数**：$x_0$ 为极值点（当 $f^{(n)}(x_0)<0$ 时取极大值；当 $f^{(n)}(x_0)>0$ 时取极小值）；
    - 若 **$n$ 为奇数**：$x_0$ **不是极值点**（而是拐点）。"""

old_inf2 = """- **拐点充分**
  - 条件一：$f$ 在 $x_0$ 连续，$f''$ 在 $x_0$ 左右去心邻域内异号 ⟹ 拐点
  - 条件二：$f''(x_0)=0,\ f'''(x_0)\\neq0$ ⟹ 拐点
  - 条件三（n 阶判别，与极值相反）：$f''(x_0)=\\cdots=f^{(n-1)}(x_0)=0,\ f^{(n)}(x_0)\\neq0$（$n\\ge3$）——$n$ 为奇数 ⟹ 拐点（例"""

new_inf2 = """- **拐点充分条件（两大充分条件判定法）**
  - **第一充分条件（二阶导变号法）**：设 $f(x)$ 在 $x_0$ 连续，在某去心邻域内二阶可导：
    - 若 $f''(x)$ 在 $x_0$ 左右去心邻域内**符号相反（异号）**，则点 $(x_0,f(x_0))$ 为**拐点**；
    - 若左右两侧 $f''(x)$ 同号，则点 $(x_0,f(x_0))$ 不是拐点。
    - 💡 适用：二阶导为 0 的点以及**二阶导不存在的点**（如 $y=\\sqrt[3]{x}$ 在 $(0,0)$ 处）。
  - **第二充分条件（高阶导数判别法）**：设 $f(x)$ 在 $x_0$ 处具有 $n$ 阶导数（$n\\ge3$），且
    $$f''(x_0)=f'''(x_0)=\\cdots=f^{(n-1)}(x_0)=0,\\quad f^{(n)}(x_0)\\neq0$$
    - 若 **$n$ 为奇数**：点 $(x_0,f(x_0))$ 为**拐点**；
    - 若 **$n$ 为偶数**：点 $(x_0,f(x_0))$ **不是拐点**（与极值判别法正好相反！记住口诀：**奇拐偶极**）。"""

assert old_ext2 in old_md2, "old_ext2 not found"
assert old_inf2 in old_md2, "old_inf2 not found"
n2['md'] = old_md2.replace(old_ext2, new_ext2).replace(old_inf2, new_inf2)

