# 1. 修正与补全 Note 1: 函数极限连续 (渐近线)
# =========================================================================
n1 = notes[1]
old_md1 = n1['md']

old_asymp1 = """## 渐近线 <!-- 源:p10 -->

- 水平：$\\lim\\limits_{x\\to\\infty}f(x)=c$（或 $x\\to\\pm\\infty$ 单侧）⟹ $y=c$（例：$\\arctan x$ 有 $y=\\pm\\frac{\\pi}{2}$ 两条）
- 垂直：$\\lim\\limits_{x\\to x_0}f(x)=\\infty$（或单侧）⟹ $x=x_0$（只需讨论**分母为零的点**或**函数无定义的端点**）
- 斜：$\\lim\\limits_{x\\to\\infty}\\frac{f(x)}{x}=a$ 且 $\\lim\\limits_{x\\to\\infty}[f(x)-ax]=b$ ⟹ $y=ax+b$（⚠️同一侧有水平渐近线就无斜渐近线）"""

new_asymp1 = """## 渐近线（三类渐近线完整判定体系） <!-- 源:p10 -->

- **1. 垂直渐近线（铅直渐近线）**：
  - **判定条件**：若 $\\lim\\limits_{x\\to x_0^+}f(x)=\\infty$ 或 $\\lim\\limits_{x\\to x_0^-}f(x)=\\infty$（单侧趋于无穷即可），则直线 $x=x_0$ 是曲线的垂直渐近线。
  - **可疑点来源**：只需在**分母为零的点**、**无定义孤立点**或**定义域有限开端点**处考察极限。
- **2. 水平渐近线**：
  - **判定条件**：若 $\\lim\\limits_{x\\to+\\infty}f(x)=c_1$（或 $\\lim\\limits_{x\\to-\\infty}f(x)=c_2$），则直线 $y=c_1$（或 $y=c_2$）为水平渐近线。
  - ⚠️ **单双侧原则**：必须**分别独立考察** $x\\to+\\infty$ 与 $x\\to-\\infty$ 两个方向（如 $\\arctan x$ 有 $y=\\pm\\frac{\\pi}{2}$ 两条水平渐近线；$e^x$ 在 $x\\to-\\infty$ 处有 $y=0$，在 $x\\to+\\infty$ 处无水平渐近线）。
- **3. 斜渐近线**：
  - **判定条件**：分别考虑 $x\\to+\\infty$ 与 $x\\to-\\infty$：
    $$a = \\lim_{x\\to+\\infty}\\frac{f(x)}{x},\\qquad b = \\lim_{x\\to+\\infty}[f(x)-ax]$$
    若 $a$（有限）且 $b$（有限）均存在，则直线 $y=ax+b$ 为 $x\\to+\\infty$ 方向的斜渐近线（$x\\to-\\infty$ 类似判定）。
  - ⭐ **渐近线互斥与极值结论**：
    - **同侧互斥**：在**同一个方向**（如 $x\\to+\\infty$ 方向），若存在水平渐近线（即 $a=0$ 且 $b=c$ 属于斜渐近线的特殊退化情形），则**不可能再有非水平的斜渐近线**；反之有斜渐近线（$a\\ne0$）也不会再有水平渐近线。
    - **不同侧独立**：正无穷方向与负无穷方向完全独立，一条曲线最多可以有 $2$ 条非垂直渐近线（左右各一），但可以有任意条垂直渐近线（如 $\\tan x$ 有无穷多条）。
  - 💡 **快速求解小技巧（拆分法）**：若 $f(x)=ax+b+\\alpha(x)$，且 $\\lim\\limits_{x\\to+\\infty}\\alpha(x)=0$，则直接得出 $y=ax+b$ 即为斜渐近线，无需重复套用极限公式。"""

assert old_asymp1 in old_md1, "old_asymp1 not found"
n1['md'] = old_md1.replace(old_asymp1, new_asymp1)


