self.addEventListener('install', (e) => {
    e.waitUntil(
        caches.open(CACHE_VER)
            // 逐张缓存 + 失败跳过：避免 addAll 全有或全无——任一资源（如 GitHub Pages 上偶发超时的图片）
            // 失败就导致整个 install 失败、新版本不激活、旧缓存继续用（表现为部分图片加载异常）
            .then(cache => Promise.allSettled(
                PRECACHE.map(url => cache.add(url)
                    .catch(err => console.warn('[sw] 预缓存失败(跳过):', url, err && err.message)))
            ))
            .then(() => self.skipWaiting())
    );
});

self.addEventListener('activate', (e) => {
    e.waitUntil(
        caches.keys()
            .then(keys => Promise.all(keys
                .filter(k => k !== CACHE_VER && k !== IMG_CACHE)      // 图片缓存单独保留
                .map(k => caches.delete(k))))
            .then(() => self.clients.claim())
    );
});

// 取策略：
//  ① sw.js 本体：永远走网络（否则旧 SW 会一直缓存住自己，更新永不生效）
//  ② 同源 HTML / JS / CSS：网络优先，失败(离线)才回落缓存 —— 保证改代码后刷新即生效
//  ③ 其它（字体/图片/数据等）：缓存优先，未命中再走网络并回填（离线可用）
// 注：不再使用 ignoreSearch，这样 HTML 里的 ?v=<hash> 能真正击穿缓存。
const NET_FIRST_RE = /\.(?:html|js|css)(?:\?.*)?$/i;
self.addEventListener('fetch', (e) => {
    if (e.request.method !== 'GET') return;
    const url = new URL(e.request.url);
    // ① sw.js 本体：绕过缓存
    if (url.origin === location.origin && url.pathname.endsWith('/sw.js')) {
        e.respondWith(fetch(e.request).catch(() => caches.match(e.request)));
        return;
    }
    // ② 同源 HTML/JS/CSS：网络优先
    if (url.origin === location.origin && NET_FIRST_RE.test(url.pathname)) {
        e.respondWith(
            fetch(e.request).then(resp => {
                if (resp.ok) {
                    const clone = resp.clone();
                    caches.open(CACHE_VER).then(cache => cache.put(e.request, clone));
                }
                return resp;
            }).catch(() => caches.match(e.request))
        );
        return;
    }
    // ③ 图片（同源 /data/img/ 或 destination=image）：走独立缓存，不随发版失效
    if (url.origin === location.origin &&
        (e.request.destination === 'image' || url.pathname.indexOf('/data/img/') >= 0)) {
        e.respondWith((async () => {
            const hit = await caches.match(e.request);      // 含预缓存里的少量图
            if (hit) return hit;
            try {
                const resp = await fetch(e.request);
                if (resp && resp.ok) {
                    const cache = await caches.open(IMG_CACHE);
                    cache.put(e.request, resp.clone());
                }
                return resp;
            } catch (err) {
                return Response.error();
            }
        })());
        return;
    }
    // ④ 其它资源：缓存优先
    e.respondWith(
        caches.match(e.request).then(hit => {
            if (hit) return hit;
            return fetch(e.request).then(resp => {
                if (resp.ok && new URL(e.request.url).origin === location.origin) {
                    const clone = resp.clone();
                    caches.open(CACHE_VER).then(cache => cache.put(e.request, clone));
                }
                return resp;
            });
        })
    );
});
